#!/usr/bin/env python3
"""Regenerate the campaign specs from sim/spec_sheet.py and the fault catalog.

The dispersion ranges in every spec mirror the spec sheet exactly, and the
mutation spec's ``[meta_sweep]`` lists every fault variant, so editing either
source and re-running this keeps the campaigns in step.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "sim"))

import spec_sheet as S  # noqa: E402
from faults import all_variants  # noqa: E402

HEADER = "# Dispersions mirror sim/spec_sheet.py (generated by harness/make_specs.py; do not hand-edit ranges).\n"


def variables() -> str:
    rows = {
        "dry_mass_kg": S.band(S.DRY_MASS_KG, S.DRY_MASS_DISP),
        "engine_tau_s": S.band(S.ENGINE_TAU_S, S.ENGINE_TAU_DISP),
        "init_altitude_m": S.INIT_ALTITUDE_M,
        "init_tilt_deg": S.INIT_TILT_DEG,
        "init_vx_mps": S.INIT_VX_MPS,
        "init_vy_mps": S.INIT_VY_MPS,
        "init_vz_mps": S.INIT_VZ_MPS,
        "init_x_m": S.INIT_X_M,
        "init_y_m": S.INIT_Y_M,
        "isp_s": S.band(S.ISP_S, S.ISP_DISP),
        "noise_seed": (0.0, 2.0**31),
        "propellant_kg": S.band(S.PROPELLANT_KG, S.PROPELLANT_DISP),
        "thrust_scale": S.band(1.0, S.THRUST_DISP),
    }
    return "\n".join(
        f'{name} = {{ dist = "uniform", min = {round(lo, 6)!r}, max = {round(hi, 6)!r} }}' for name, (lo, hi) in rows.items()
    )


def spec(n: int, seed: int, comment: str, extra: str = "") -> str:
    return (
        f"{HEADER}# {comment}\n"
        f'[monte_carlo]\nn_samples = {n}\nseed = {seed}\nmethod = "lhs"\n\n'
        f"[monte_carlo.variables]\n{variables()}\n{extra}"
    )


def main() -> None:
    out = ROOT / "campaigns"
    (out / "dev.toml").write_text(
        spec(40, 7, "Development / calibration set: used to tune the FSW and the two closed-loop check tolerances.")
    )
    (out / "clean.toml").write_text(
        spec(200, 20261104, "Clean holdout: 200 dispersed runs, no faults, never used for tuning. Any flag here is a false positive.")
    )
    faults = ",\n    ".join(f'"{v}"' for v in ["none", *all_variants()])
    (out / "mutation.toml").write_text(
        spec(
            40,
            1969,
            "Mutation campaign: every fault variant x the same 40 dispersion samples, plus fault = none as each sample's clean twin.",
            f"\n[meta_sweep]\nfault = [\n    {faults},\n]\n",
        )
    )
    (out / "smoke.toml").write_text(
        spec(1, 11, "Smoke test: one dispersion sample per fault variant, to check every fault is wired through.",
             f"\n[meta_sweep]\nfault = [\n    {faults},\n]\n")
    )
    print(f"wrote dev.toml, clean.toml, mutation.toml, smoke.toml ({len(all_variants())} fault variants)")


if __name__ == "__main__":
    main()
